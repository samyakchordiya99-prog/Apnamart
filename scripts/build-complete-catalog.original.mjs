// 2. Write CSV files in project folder
function escapeCsv(val) {
  if (val === null || val === undefined) return '';
  const s = String(val);
  if (s.includes(',') || s.includes('"') || s.includes('\n')) {
    return `"${s.replace(/"/g, '""')}"`;
  }
  return s;
}

function generateCsv(products) {
  const headers = [
    'productId',
    'shopId',
    'shopName',
    'productName',
    'category',
    'brand',
    'description',
    'quantityOrPack',
    'mrp',
    'discountPercent',
    'sellingPrice',
    'stockQuantity',
    'unit',
    'imageUrl',
    'isAvailable',
    'isDemoData',
    'createdAt',
    'updatedAt'
  ];

  const rows = [headers.join(',')];
  for (const p of products) {
    const row = headers.map(h => escapeCsv(p[h]));
    rows.push(row.join(','));
  }
  return rows.join('\n');
}


// Helper to assemble product records
function compileProducts(rawList, shopId, shopName) {
  return rawList.map((item, index) => {
    const pad = String(index + 1).padStart(3, '0');
    const productId = `${shopId}_PROD_${pad}`;
    const sellingPrice = getPrice(item.mrp, item.off);
    const createdAt = Date.now() - (rawList.length - index) * 60000;

    return {
      id: productId,
      productId,
      shopId,
      shopName,
      name: item.name,
      productName: item.name,
      category: item.cat,
      brand: item.brand,
      description: item.desc,
      quantityOrPack: item.pack,
      mrp: item.mrp,
      discountPercent: item.off,
      sellingPrice,
      price: sellingPrice,
      stockQuantity: item.stock,
      stock: item.stock,
      availableStock: item.stock,
      unit: item.unit,
      imageUrl: item.img,
      isAvailable: item.stock > 0,
      isDemoData: true,
      availabilityStatus: item.stock > 0 ? 'in_stock' : 'out_of_stock',
      createdAt,
      updatedAt: createdAt,
    };
  });
}

